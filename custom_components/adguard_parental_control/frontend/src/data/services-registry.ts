/**
 * Look up a known service by hostname.
 * Checks each registered domain; returns null for unknown domains.
 */
export function lookupService(host: string): ServiceEntry | null {
  const h = host.toLowerCase().replace(/\.$/, "");
  for (const svc of SERVICES) {
    for (const d of svc.domains) {
      if (h === d || h.endsWith("." + d)) return svc;
    }
  }
  return null;
}

